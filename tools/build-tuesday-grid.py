"""Generate the OBS and browser shaders from one shared rendering body."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]/'overlays/tech-talks-tuesday'
body=(root/'grid-surface.shader').read_text()
# Where the scene underneath changes, as a fraction of the run: inside the
# edge-on line. fusion.js switches the layout at the same fraction.
CUT=0.47
native='''/* Generated by tools/build-tuesday-grid.py. Edit grid-surface.shader. */
uniform float Progress < string label = "Manual progress (-1 = automatic)"; float minimum = -1.0; float maximum = 1.0; float step = 0.001; > = -1.0;
uniform float Duration < string label = "Duration in seconds"; float minimum = 0.5; float maximum = 3.0; float step = 0.05; > = 1.8;
uniform float Grid_Columns < string label = "Grid columns"; float minimum = 40.0; float maximum = 180.0; float step = 1.0; > = 96.0;
uniform float Relief < string label = "Relief height"; float minimum = 0.0; float maximum = 0.4; float step = 0.01; > = 0.18;
uniform float Wave < string label = "Wave height"; float minimum = 0.0; float maximum = 0.4; float step = 0.01; > = 0.16;
float4 sampleScene(float2 uv, float raw) { return image.SampleLevel(textureSampler, uv, 0.0); }
'''+body+'''
float4 mainImage(VertData v_in) : TARGET {
  float raw = Progress >= 0.0 ? saturate(Progress) : saturate(elapsed_time_enable / Duration);
  return renderGrid(v_in.uv, raw, uv_size.x / uv_size.y, Grid_Columns, Relief, Wave);
}
'''
(root/'grid-bend.shader').write_text(native)
webbody=body
for a,b in [('float4','vec4'),('float3','vec3'),('float2','vec2'),('lerp(','mix('),('frac(','fract('),('ddx(','dFdx('),('ddy(','dFdy(')]:webbody=webbody.replace(a,b)
web='''#version 300 es
precision highp float;
in vec2 screenUV;out vec4 outputColor;
uniform sampler2D sceneA;uniform sampler2D sceneB;uniform float progress;
float saturate(float x){return clamp(x,0.,1.);}
vec4 sampleScene(vec2 uv,float raw){return raw<%s?textureLod(sceneA,uv,0.):textureLod(sceneB,uv,0.);}
''' % CUT+webbody+'''
void main(){outputColor=renderGrid(screenUV,clamp(progress,0.,1.),1920./1080.,96.,.18,.16);}
'''
(root/'grid-preview.frag').write_text(web)
print('Generated native HLSL and browser GLSL from grid-surface.shader.')
